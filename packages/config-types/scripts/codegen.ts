/**
 * Generates this package's files from the engine's config schemas (architecture A9: the Rust
 * types are the single source of truth). Used by `generate.ts` (writes the files) and by
 * `codegen.test.ts` (fails when the committed files are out of date).
 */
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { isDeepStrictEqual } from "node:util";

import { compile, type JSONSchema } from "json-schema-to-typescript";

/** Root of this package (`packages/config-types`). */
export const PACKAGE_DIR = join(import.meta.dirname, "..");
const REPO_DIR = join(PACKAGE_DIR, "../..");

/** The schema files the engine writes, without their directory. */
const SCHEMA_FILES = ["profile.v1.json", "settings.v1.json"] as const;

/** A file this package should contain: path relative to the package, and its text. */
export type GeneratedFile = { path: string; text: string };

/**
 * Asks the current engine source for its schemas: builds the CLI if needed and runs
 * `keyrift schema --out <tmp>`. Returns file name → parsed schema.
 */
function readEngineSchemas(): Map<string, JSONSchema> {
  const out = mkdtempSync(join(tmpdir(), "keyrift-schema-"));
  try {
    execFileSync(
      "cargo",
      ["run", "--quiet", "--package", "keyrift", "--", "schema", "--out", out],
      {
        cwd: REPO_DIR,
        stdio: ["ignore", "ignore", "inherit"],
      },
    );
    const schemas = new Map<string, JSONSchema>();
    for (const file of SCHEMA_FILES) {
      schemas.set(file, JSON.parse(readFileSync(join(out, file), "utf8")) as JSONSchema);
    }
    return schemas;
  } finally {
    rmSync(out, { recursive: true, force: true });
  }
}

/**
 * Puts both schemas into one, so types they share (`KeyName`, `Strategy`, …) are generated once.
 * The root types become `$defs.Profile` and `$defs.Settings`.
 */
function mergeSchemas(profile: JSONSchema, settings: JSONSchema): JSONSchema {
  const defs: Record<string, JSONSchema> = {};
  for (const [name, schema] of [
    ["Profile", profile],
    ["Settings", settings],
  ] as const) {
    const { $defs, ...root } = schema as JSONSchema & { $defs?: Record<string, JSONSchema> };
    for (const [key, def] of Object.entries($defs ?? {})) {
      if (key in defs && !isDeepStrictEqual(defs[key], def)) {
        throw new Error(`$defs.${key} differs between the profile and settings schemas`);
      }
      defs[key] = def;
    }
    defs[name] = root;
  }
  return {
    title: "ConfigFiles",
    type: "object",
    properties: {
      profile: { $ref: "#/$defs/Profile" },
      settings: { $ref: "#/$defs/Settings" },
    },
    required: ["profile", "settings"],
    additionalProperties: false,
    $defs: defs,
  };
}

/** Formats a file's text with the repo's formatter, as `vp check` expects it. */
function format(text: string, fileName: string): string {
  return execFileSync("vp", ["fmt", "--stdin-filepath", fileName], {
    cwd: PACKAGE_DIR,
    input: text,
    encoding: "utf8",
  });
}

/** Everything this package generates, in memory. */
export async function generate(): Promise<GeneratedFile[]> {
  const schemas = readEngineSchemas();
  const profile = schemas.get("profile.v1.json");
  const settings = schemas.get("settings.v1.json");
  if (profile === undefined || settings === undefined) {
    throw new Error("the engine did not write both schemas");
  }
  const types = await compile(mergeSchemas(profile, settings), "ConfigFiles", {
    bannerComment:
      "/* Generated by scripts/generate.ts from the engine's JSON Schemas. Do not edit. */",
    additionalProperties: false,
    format: false,
  });
  const files: GeneratedFile[] = [
    { path: "src/generated/types.ts", text: format(types, "src/generated/types.ts") },
  ];
  for (const [file, schema] of schemas) {
    const path = `schema/${file}`;
    files.push({ path, text: format(JSON.stringify(schema), path) });
  }
  return files;
}
