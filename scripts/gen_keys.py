#!/usr/bin/env python3
"""Generate crates/core/src/keys_generated.rs from linux/input-event-codes.h.

Only numeric KEY_* defines below 560 are included: uinput devices cannot reliably
advertise higher codes (same limit kanata uses). The first name defined for a code
is its canonical name; later numeric duplicates are ignored.

Usage: python3 -I scripts/gen_keys.py [/usr/include/linux/input-event-codes.h]
"""
import pathlib
import re
import sys

MAX_CODE = 560
SKIP = {"KEY_RESERVED", "KEY_MAX", "KEY_CNT", "KEY_MIN_INTERESTING"}

header = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "/usr/include/linux/input-event-codes.h")
pattern = re.compile(r"^#define\s+(KEY_[A-Z0-9_]+)\s+(0x[0-9a-fA-F]+|\d+)\b")
entries = []
for line in header.read_text().splitlines():
    m = pattern.match(line)
    if not m or m.group(1) in SKIP:
        continue
    code = int(m.group(2), 0)
    if 0 < code < MAX_CODE:
        entries.append((m.group(1), code))

seen = set()
canonical = []
for name, code in entries:
    if code not in seen:
        canonical.append((name, code))
    seen.add(code)

root = pathlib.Path(__file__).resolve().parent.parent
out = root / "crates/core/src/keys_generated.rs"
lines = [
    "// @generated by scripts/gen_keys.py from linux/input-event-codes.h. Do not edit by hand.",
    "",
    "/// Canonical evdev key names and codes, sorted by code.",
    "pub(crate) const CANONICAL: &[(&str, u16)] = &[",
]
lines += [f'    ("{n}", {c}),' for n, c in sorted(canonical, key=lambda e: e[1])]
lines += ["];", ""]
out.write_text("\n".join(lines))
print(f"wrote {out} ({len(canonical)} keys)")
